/**
 * The HR user guide, written from the screens as they are today. Each procedure is a list of numbered steps; a step can carry a
 * picture (a real screenshot of the system with made-up data, numbered markers drawn on it, saved under public/help/).
 * Payroll and payslips are left out until that menu is switched on (see navigation.ts).
 */

export interface GuideImage {
  /** Path under public/, for example "/help/employees-add-1.png". */
  src: string;
  /** What the picture shows, for people who cannot see it. */
  alt: string;
  /** One entry per numbered marker drawn on the picture, in order (1, 2, 3 ...): [what it is, what to do with it]. */
  legend: [label: string, text: string][];
}

export interface GuideStep {
  text: string;
  /** Short extra lines under the step. */
  sub?: string[];
  image?: GuideImage;
}

export interface Procedure {
  title: string;
  /** Where to find it, written the way the menu reads: "พนักงาน › รายชื่อพนักงาน". */
  where?: string;
  steps: GuideStep[];
}

export interface GuideTable {
  caption: string;
  headers: string[];
  rows: string[][];
}

export interface GuideSection {
  id: string;
  title: string;
  icon: LucideIcon;
  intro?: string;
  procedures?: Procedure[];
  tables?: GuideTable[];
  tips?: string[];
}

