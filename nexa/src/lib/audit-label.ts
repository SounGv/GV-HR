export function auditActionLabel(code: string): string {
  const dot = code.indexOf(".");
  if (dot < 0) return code;
  const noun = NOUN[code.slice(0, dot)];
  const verb = VERB[code.slice(dot + 1)];
  if (!noun || !verb) return code;
  return `${verb} ${noun}`;
}

